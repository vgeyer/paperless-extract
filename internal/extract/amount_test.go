package extract_test

import (
	"errors"
	"testing"

	"github.com/shopspring/decimal"

	"github.com/vgeyer/paperless-extract/internal/extract"
)

func TestParseAmount(t *testing.T) {
	cases := []struct {
		in   string
		want string
	}{
		// §8.1 table
		{"1.234,56", "1234.56"},
		{"1,234.56", "1234.56"},
		{"1234,56", "1234.56"},
		{"1234.56", "1234.56"},
		{"1 234,56", "1234.56"},
		{"1 234,56", "1234.56"},
		{"1 234,56", "1234.56"},
		{"1 234,56", "1234.56"},
		{"1'234.56", "1234.56"},
		{"1’234.56", "1234.56"},
		{"€ 1.234,56", "1234.56"},
		{"1.234,56 €", "1234.56"},
		{"EUR1234.56", "1234.56"},
		{"1.234,56 EUR.", "1234.56"},
		{"CHF 1'234.50", "1234.5"},
		{"Fr. 1'234.50", "1234.5"},
		{"1234.-", "1234"},
		{"1.234,-", "1234"},
		{"1.234,--", "1234"},
		{"50,–", "50"},
		{"0,99", "0.99"},
		{"12,5", "12.5"},
		{"1,23", "1.23"},
		{"1234", "1234"},
		{"1.234", "1234"},
		{"1,234", "1234"},
		{"12.345", "12345"},
		{"999.999", "999999"},
		{"0,125", "0.125"},
		{"1234,567", "1234.567"},
		{"123,4567", "123.4567"},
		{"1 234.567", "1234.567"},
		{"1.234.567", "1234567"},
		{"1 234 567", "1234567"},
		{"1.234.567,89", "1234567.89"},
		{"1,234,567.89", "1234567.89"},
		{"1.234,5", "1234.5"},
		{"-1.234,56", "-1234.56"},
		{"1.234,56-", "-1234.56"},
		{"(1.234,56)", "-1234.56"},
		{"−12,00", "-12"},
		{"- 12,00 EUR", "-12"},
		{"+12,00", "12"},
		// additional edge cases derived from the algorithm
		{"  1.234,56  ", "1234.56"},
		{"€1.234,56", "1234.56"},
		{"1.234,56€", "1234.56"},
		{"$1,234.56", "1234.56"},
		{"£ 99.99", "99.99"},
		{"PLN 1 234,56", "1234.56"},
		{"1 234,56 zł", "1234.56"},
		{"Kč 1 234,00", "1234"},
		{"EUR: 12,00", "12"},
		{"(1.234,56 €)", "-1234.56"},
		{"1234,-", "1234"},
		{"1.234,–", "1234"},
		{"50.—", "50"},
		{"0.125", "0.125"},
		{"0,5", "0.5"},
		{"1,2345", "1.2345"},
		{"1'234'567.00", "1234567"},
		{"1 234 567,89", "1234567.89"},
		{"12'345", "12345"},
		{"1.234,567", "1234.567"},
		{"7", "7"},
		{"000,99", "0.99"},
		{"1.000.000,00", "1000000"},
	}
	for _, c := range cases {
		got, err := extract.ParseAmount(c.in)
		if err != nil {
			t.Errorf("ParseAmount(%q) error: %v", c.in, err)
			continue
		}
		if want := decimal.RequireFromString(c.want); !got.Equal(want) {
			t.Errorf("ParseAmount(%q) = %s, want %s", c.in, got, want)
		}
	}
}

func TestParseAmountErrors(t *testing.T) {
	bad := []string{
		// §8.1 table
		"", "   ", "€", "abc", ".50", "--12", "-(12)",
		"1.23.45", "12 50", "1..234", "1,234.567,89", "1.234,56.78",
		"1.234 567", "12,00 + 3,00",
		// additional
		",50",
		"12.34.56",
		"1,23,456",
		"1234.567.890",
		"1.2345.678",
		"1. 234",
		"1,,5",
		"1_234",
		"12a34",
		"1.234,56,78",
		"(12",
		"12)",
		"((12))",
		"-12-",
		"+-12",
		"1'234,567.00,5",
		"12.345,678.9",
		"1 234'567",
		"1.234'567,00",
		"12,",
		"1,234,56",
		"1234 567,00",
	}
	for _, in := range bad {
		got, err := extract.ParseAmount(in)
		if err == nil {
			t.Errorf("ParseAmount(%q) = %s, want error", in, got)
			continue
		}
		if !errors.Is(err, extract.ErrInvalidAmount) {
			t.Errorf("ParseAmount(%q) error %v does not wrap ErrInvalidAmount", in, err)
		}
	}
}
